#!/usr/bin/env python3
"""Log an answered Snowflake question back into this skill, via a pull request.

Appends a dated entry to QUESTION_LOG.md, adds a row to the
"Known questions -> guidepaths" table in SKILL.md, commits both to a new branch
and opens a PR against the repository's default branch.

Uses the GitHub REST API with GIT_TOKEN -- no gh CLI, no local clone required.

Usage:
    python3 scripts/log_question.py \
      --question "What was total wholesale cost by customer?" \
      --route "PUBLIC_AGGREGATED.SNOWFLAKE_ORDERS_SUMMARY -> sum(total_wholesale_cost)" \
      --sql "select bill_customer_sk_id, sum(total_wholesale_cost) ... " \
      --caveat "first_order_date = last_order_date for all rows"
"""
import argparse
import base64
import datetime as dt
import json
import os
import re
import sys
import urllib.error
import urllib.request

API = "https://api.github.com"
DEFAULT_REPO = "orchestra-hq/orchestra-skills"
DEFAULT_DIR = "skills/orchestra/skills/ask-snowflake-question"
ATTRIBUTION = (
    "Generated by an [Orchestra agent](https://app.getorchestra.io/agents/sessions/"
    + os.environ.get("ORCHESTRA_AGENT_SESSION_ID", "")
    + ")"
)


def api(method, path, token, body=None):
    url = path if path.startswith("http") else API + path
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, method=method)
    req.add_header("Authorization", f"Bearer {token}")
    req.add_header("Accept", "application/vnd.github+json")
    if data:
        req.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(req) as r:
            raw = r.read()
            return json.loads(raw) if raw else {}
    except urllib.error.HTTPError as e:
        detail = e.read().decode(errors="replace")[:400]
        raise SystemExit(f"GitHub {method} {url} failed: {e.code} {detail}")


def get_file(repo, path, ref, token):
    """Return (text, blob_sha). Raises if missing."""
    r = api("GET", f"/repos/{repo}/contents/{path}?ref={ref}", token)
    return base64.b64decode(r["content"]).decode(), r["sha"]


def put_file(repo, path, text, sha, branch, message, token):
    api(
        "PUT",
        f"/repos/{repo}/contents/{path}",
        token,
        {
            "message": message,
            "content": base64.b64encode(text.encode()).decode(),
            "sha": sha,
            "branch": branch,
        },
    )


def cell(s, limit=220):
    """Make a string safe for a one-line markdown table cell."""
    s = " ".join((s or "").split()).replace("|", "\\|")
    return s[: limit - 1] + "…" if len(s) > limit else s


def add_guidepath_row(skill_md, date, question, route, caveat):
    """Insert a row at the end of the guidepaths table in SKILL.md."""
    row = f"| {date} | {cell(question)} | {cell(route)} | {cell(caveat) or '—'} |"
    if cell(question) in skill_md:
        return skill_md, False  # already logged, keep it idempotent

    lines = skill_md.rstrip("\n").split("\n")
    # find the last contiguous block of table rows at/after the guidepaths heading
    try:
        start = next(
            i for i, l in enumerate(lines) if l.strip().lower().startswith("## known questions")
        )
    except StopIteration:
        raise SystemExit("SKILL.md has no '## Known questions' section to append to.")

    end = start
    for i in range(start, len(lines)):
        if lines[i].lstrip().startswith("|"):
            end = i
    lines.insert(end + 1, row)
    return "\n".join(lines) + "\n", True


def append_log(log_md, date, question, route, sql, caveat, answer):
    entry = [f"\n## {date} — {question.strip()}\n"]
    entry.append(f"**Route:** {route.strip()}\n")
    if answer:
        entry.append(f"**Answer:** {answer.strip()}\n")
    if caveat:
        entry.append(f"**Caveat:** {caveat.strip()}\n")
    if sql:
        entry.append("```sql\n" + sql.strip() + "\n```\n")
    return log_md.rstrip("\n") + "\n" + "\n".join(entry)


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:40] or "question"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--question", required=True)
    ap.add_argument("--route", required=True, help="tables and shape of the answer")
    ap.add_argument("--sql", default="", help="the SQL actually run")
    ap.add_argument("--caveat", default="", help="data-quality or PII caveat found")
    ap.add_argument("--answer", default="", help="short form of the answer given")
    ap.add_argument("--repo", default=os.environ.get("SKILL_REPO", DEFAULT_REPO))
    ap.add_argument("--dir", default=os.environ.get("SKILL_DIR", DEFAULT_DIR))
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    token = os.environ.get("GIT_TOKEN")
    if not token and not args.dry_run:
        sys.exit("GIT_TOKEN is not set; cannot open a pull request.")

    date = dt.date.today().isoformat()
    skill_path = f"{args.dir}/SKILL.md"
    log_path = f"{args.dir}/QUESTION_LOG.md"

    repo_info = api("GET", f"/repos/{args.repo}", token)
    base = repo_info["default_branch"]

    skill_md, skill_sha = get_file(args.repo, skill_path, base, token)
    log_md, log_sha = get_file(args.repo, log_path, base, token)

    skill_new, changed = add_guidepath_row(
        skill_md, date, args.question, args.route, args.caveat
    )
    log_new = append_log(
        log_md, date, args.question, args.route, args.sql, args.caveat, args.answer
    )

    if args.dry_run:
        print("--- SKILL.md guidepath row added:", changed)
        print(skill_new[-1200:])
        print("--- QUESTION_LOG.md tail:")
        print(log_new[-1200:])
        return

    branch = f"log-question/{date}-{slug(args.question)}"
    base_sha = api("GET", f"/repos/{args.repo}/git/ref/heads/{base}", token)["object"]["sha"]
    api(
        "POST",
        f"/repos/{args.repo}/git/refs",
        token,
        {"ref": f"refs/heads/{branch}", "sha": base_sha},
    )

    put_file(args.repo, log_path, log_new, log_sha, branch,
             f"log: {args.question}", token)
    if changed:
        put_file(args.repo, skill_path, skill_new, skill_sha, branch,
                 f"guidepath: {args.question}", token)

    body = (
        f"Logs a Snowflake question answered on {date} and adds its guidepath so the "
        f"next person can skip rediscovery.\n\n"
        f"**Question:** {args.question}\n\n"
        f"**Route:** {args.route}\n\n"
        + (f"**Caveat:** {args.caveat}\n\n" if args.caveat else "")
        + (f"```sql\n{args.sql}\n```\n\n" if args.sql else "")
        + ATTRIBUTION
    )
    pr = api(
        "POST",
        f"/repos/{args.repo}/pulls",
        token,
        {"title": f"Log Snowflake question: {args.question}"[:72],
         "head": branch, "base": base, "body": body},
    )
    print(f"Opened PR #{pr['number']}: {pr['html_url']}")


if __name__ == "__main__":
    main()
